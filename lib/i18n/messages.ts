export const messages: Record<Locale, typeof zh> = { zh, en };

type Params = Record<string, string | number>;

/** 按点路径取字典值，支持 {x} 占位符插值；缺失时回退中文，再回退 key 本身。 */
export function translate(locale: Locale, key: string, params?: Params): string {
  const pick = (dict: any) =>
    key.split(".").reduce((o: any, k) => (o == null ? undefined : o[k]), dict);

  let val = pick(messages[locale] ?? messages.zh);
  if (typeof val !== "string") val = pick(messages.zh);
  if (typeof val !== "string") return key;

  if (params) {
    val = val.replace(/\{(\w+)\}/g, (_m: string, k: string) =>
      params[k] != null ? String(params[k]) : `{${k}}`
    );
  }
  return val;
}
